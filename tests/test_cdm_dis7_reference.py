"""T16 / A13: the `dis7` codec and adapter against open-dis-python's own serialisation and parse.

Two halves. The always-on half needs nothing outside the repository: the packaged PDUs are the
bytes the handoff bundle records as OpenDIS-generated, the pin record states the independent
reading, the `reference` marker is registered, a missing checkout is a BLOCKED skip, and the
generator's scenarios are the packaged envelopes' twins. The live half carries
`@pytest.mark.reference` and asks for the pinned open-dis-python checkout through
`tests/dis7_reference_support.py`; without it each live test is SKIPPED with a reason beginning
`BLOCKED_EXTERNAL_EVIDENCE` — never passed. OpenDIS runs only in a child interpreter.
"""
