@pytest.mark.reference
def test_t16_a13_255_records_agree_in_both_directions():
    directory = support.checkout()
    scenario = _scenario("equator_eastbound")
    scenario["records"] = [[k, float(k), k * 65537, k, k] for k in range(255)]
    expected = [struct.pack(">BdIHB", k, float(k), k * 65537, k, k).hex() for k in range(255)]
    raw = support.build(directory, scenario)
    assert len(raw) == 4224
    assert raw[19] == 255
    adapter = Dis7Adapter.fixture_instance()
    objects = adapter.to_cdm(raw)
    assert len(objects) == 1
    assert objects[0].residual.data["pdu"]["variable_parameters_hex"] == expected
    assert adapter.from_cdm(objects) == raw
    answer = support.parse(directory, raw)
    assert answer["reserialised_hex"] == raw.hex()
    assert answer["fields"]["variable_parameters_hex"] == expected


