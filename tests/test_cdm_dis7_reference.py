@pytest.mark.reference
@pytest.mark.parametrize("stem", STEMS)
def test_t16_a13_opendis_parse_equals_decode_pdu_field_by_field(stem):
    directory = support.checkout()
    fields = support.parse(directory, vector_bytes(stem))["fields"]
    ours = decode_pdu(vector_bytes(stem))
    assert set(fields) == set(ours)
    assert set(fields["header"]) == set(ours["header"])
    for key in ours["header"]:
        assert fields["header"][key] == ours["header"][key], f"header.{key}"
    for key in ours:
        assert fields[key] == ours[key], key
    assert canonical.serialise(fields) == canonical.serialise(ours)


