PIN_RECORD = FIXTURES / "spec" / "dis7_pin.json"

#: Length and SHA-256 of each packaged PDU, as the bundle's vector index records the
#: OpenDIS-generated bytes. Literals, never computed from the files.
RECORDED = {
    "equator_eastbound": (144, "c958233bda22e82385788584e0297d0e264ee2a0db94dc32838141925155ef1a"),
    "north_pole_stationary": (
        144, "e7354d35aab73b5e372c13dbf9c946ed57a53dadb1e11f3b218eadf402f00fc7"),
    "unprojectable_with_extensions": (
        160, "4397c9e4f90188a7eee7ceba7abad8a0a5c2c65c3108a3110e5157539507912d"),
}

ALL_EQUAL = ("3 vectors regenerated through open-dis-python "
             "732b6655bb47e34ccc73722eefe0f4706fd0032f: all equal the packaged files")


def _pin_record() -> dict:
    return json.loads(PIN_RECORD.read_text())


def _scenario(stem: str) -> dict:
    return json.loads(json.dumps(support.generator().SCENARIOS[stem]))


def _local_path_with_sha256(node) -> list:
    if isinstance(node, dict):
        found = [node] if "local_path" in node and "sha256" in node else []
        for value in node.values():
            found += _local_path_with_sha256(value)
        return found
    if isinstance(node, list):
        return [hit for value in node for hit in _local_path_with_sha256(value)]
    return []


# ======================================================================== always on

@pytest.mark.parametrize("stem", STEMS)
def test_t16_a13_packaged_vectors_are_the_recorded_opendis_bytes(stem):
    raw = vector_bytes(stem)
    size, sha = RECORDED[stem]
    assert len(raw) == size
    assert hashlib.sha256(raw).hexdigest() == sha
    rows = [row for row in _pin_record()["vectors"]["files"] if row["file"] == f"vectors/{stem}.dis"]
    assert len(rows) == 1, rows
    assert rows[0]["sha256"] == sha
    assert rows[0]["bytes"] == size


def test_t16_a13_pin_record_states_the_independent_reading():
    record = _pin_record()
    block = record["independent_reading_tool"]
    assert set(block) == {"status", "tool", "version", "taken_on", "environment", "what_it_shows"}
    if block["status"] == "TAKEN":
        assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", block["taken_on"])
        assert set(block["environment"]) == {"python", "platform", "git", "opendis"}
        for key, value in block["environment"].items():
            assert isinstance(value, str) and value.strip(), key
        assert support.PIN in block["environment"]["opendis"]
    else:
        assert block["status"] == "BLOCKED_EXTERNAL_EVIDENCE"
        assert block["version"] is None
        assert block["taken_on"] is None
        assert block["environment"] is None
    assert _local_path_with_sha256(record) == []


