def _empty_directory(tmp_path):
    return tmp_path


def _opendis_without_git(tmp_path):
    (tmp_path / "opendis").mkdir()
    (tmp_path / "opendis" / "dis7.py").write_text("")
    return tmp_path


@pytest.mark.parametrize("case, make, expected", [
    ("unset", None, "BLOCKED_EXTERNAL_EVIDENCE at step 'hook': SYNAPSE_CDM_OPENDIS_DIR is not set"),
    ("empty_directory", _empty_directory, "BLOCKED_EXTERNAL_EVIDENCE at step 'directory': "),
    ("no_git", _opendis_without_git, "BLOCKED_EXTERNAL_EVIDENCE at step 'record': "),
])
def test_t16_a13_blocked_reasons(case, make, expected, monkeypatch, tmp_path):
    if make is None:
        monkeypatch.delenv(support.ENV_VAR, raising=False)
    else:
        monkeypatch.setenv(support.ENV_VAR, str(make(tmp_path)))
    with pytest.raises(pytest.skip.Exception) as caught:
        support.checkout()
    if make is None:
        assert str(caught.value) == expected
    else:
        assert str(caught.value).startswith(expected), str(caught.value)


@pytest.mark.parametrize("stem", STEMS)
def test_t16_a13_generator_scenarios_are_the_packaged_twins(stem):
    module = support.generator()
    pdu = vector_json(stem, "envelope")["pdu"]
    assert list(module.SCENARIOS) == list(STEMS)
    assert module.REFERENCE_COMMIT == support.PIN
    scenario = module.SCENARIOS[stem]
    assert scenario["entity_id"] == pdu["entity_id"]
    assert scenario["force_id"] == pdu["force_id"]
    assert scenario["appearance"] == pdu["appearance"]
    assert scenario["capabilities"] == pdu["capabilities"]
    assert scenario["orientation"] == pdu["orientation_radians"]
    assert scenario["position"] == pdu["position_ecef_m"]
    assert scenario["exercise_id"] == pdu["header"]["exercise_id"]
    assert scenario["timestamp"] == pdu["header"]["timestamp"]
    assert scenario["status"] == pdu["header"]["status"]
    assert [scenario["entity_kind"], scenario["domain"], scenario["country"],
            scenario["category"]] == pdu["entity_type"][:4]
    assert struct.pack(">3f", *scenario["velocity"]) == struct.pack(">3f", *pdu["velocity_mps"])
    assert scenario["dead_reckoning_algorithm"] == int(pdu["dead_reckoning_hex"][:2], 16)
    assert (bytes([scenario["marking_character_set"]])
            + scenario["marking"].encode("ascii")).hex() == pdu["marking_hex"]
    assert [struct.pack(">BdIHB", *r).hex() for r in scenario["records"]] == \
        pdu["variable_parameters_hex"]
    assert not [name for name in sys.modules if name == "opendis" or name.startswith("opendis.")]


